export function scenarioProblems(scenarios = TROUBLESHOOTING_SCENARIOS) {
  const problems = [];
  scenarios.forEach((item) => {
    if (!item.nodes?.[item.start]) problems.push(`${item.id} has no start node`);
    const diagnosisIds = new Set((item.diagnoses || []).map((row) => row.id));
    if (!diagnosisIds.has(item.rootCauseId)) problems.push(`${item.id} root cause is not a diagnosis`);
    Object.entries(item.nodes || {}).forEach(([nodeId, node]) => {
      (node.checks || []).forEach((check) => {
        if (!item.nodes[check.next]) problems.push(`${item.id} ${nodeId} ${check.id} points nowhere`);
      });
    });
    const hidden = `${item.rootCause} ${item.fix} ${item.why}`;
    const visible = [item.summary, ...(item.symptoms || [])].join(' ');
    if (visible.includes(item.fix)) problems.push(`${item.id} shows the fix before a diagnosis`);
    if (hidden.trim().length < 20) problems.push(`${item.id} explanation is too short`);
  });
  return problems;
}
