function scenario(s) {
  return {
    id: s.id,
    title: s.title,
    category: s.category,
    difficulty: s.difficulty,
    summary: s.summary,
    symptoms: s.symptoms,
    start: 'first',
    nodes: {
      first: {
        prompt: s.firstPrompt,
        checks: [
          { id: 'right', label: s.rightLabel, feedback: s.rightFeedback, next: 'second', useful: true },
          { id: 'wrong', label: s.wrongLabel, feedback: s.wrongFeedback, next: 'first', useful: false, hint: s.wrongHint },
        ],
      },
      second: {
        prompt: s.secondPrompt,
        checks: [
          { id: 'confirm', label: s.confirmLabel, feedback: s.confirmFeedback, next: 'second', useful: true },
          { id: 'detour', label: s.detourLabel, feedback: s.detourFeedback, next: 'first', useful: false, hint: s.detourHint },
        ],
      },
    },
    diagnoses: s.diagnoses,
    rootCauseId: s.rootCauseId,
    rootCause: s.rootCause,
    fix: s.fix,
    why: s.why,
  };
}

